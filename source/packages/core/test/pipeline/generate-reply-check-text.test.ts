import { describe, expect, it } from 'vitest';
import { headingsOf } from '../../src/pipeline/generate/headings.js';
import type { GeneratedPlan, PlannedFile } from '../../src/pipeline/generate/plan.js';
import { checkReply } from '../../src/pipeline/generate/reply-check.js';

function file(path: string, layout = `layout of ${path}`): PlannedFile {
  return { path, layout, description: '', ruleTags: [] };
}

const DOC_LAYOUT = '# Project\n\n## Goal\n\nText.\n\n### Detail\n\n## Rules\n';
const PLAN: GeneratedPlan = {
  files: [file('CLAUDE.md', DOC_LAYOUT), file('.claude/commands/pipeline.md'), file('.claude/rules/general.md')],
};

function replyOf(entries: readonly (readonly [string, unknown])[]): Map<string, unknown> {
  return new Map(entries);
}

const VALID_TEXT = '# Project\n\n## Goal\n\nSome goal.\n\n## Rules\n\nRules here.';

describe('F-04 reply check of the text', () => {
  it('F-04 AC-025 returns no findings when every Markdown heading is a whole line of its text', () => {
    const reply = replyOf([
      ['CLAUDE.md', VALID_TEXT],
      ['.claude/commands/pipeline.md', 'Run the pipeline.'],
      ['.claude/rules/general.md', 'General rules.'],
    ]);
    expect(checkReply(PLAN, reply)).toEqual([]);
  });

  it('F-04 AC-030 names the path and the heading that the Markdown text lacks', () => {
    const reply = replyOf([
      ['CLAUDE.md', '# Project\n\n## Goal\n\nSome goal.'],
      ['.claude/commands/pipeline.md', 'Run the pipeline.'],
      ['.claude/rules/general.md', 'General rules.'],
    ]);
    expect(checkReply(PLAN, reply)).toEqual([{ path: 'CLAUDE.md', message: 'is missing the heading "## Rules"' }]);
  });

  it('F-04 AC-030 does not count a ### line as the ## heading it is nested under', () => {
    const reply = replyOf([
      ['CLAUDE.md', '# Project\n\n### Goal\n\n### Rules\n'],
      ['.claude/commands/pipeline.md', 'Run the pipeline.'],
      ['.claude/rules/general.md', 'General rules.'],
    ]);
    expect(checkReply(PLAN, reply)).toEqual([
      { path: 'CLAUDE.md', message: 'is missing the heading "## Goal"' },
      { path: 'CLAUDE.md', message: 'is missing the heading "## Rules"' },
    ]);
  });

  it('F-04 AC-030 does not count a heading that is only part of a line', () => {
    const reply = replyOf([
      ['CLAUDE.md', '# Project\n\n## Goal\n\nSee ## Rules below.'],
      ['.claude/commands/pipeline.md', 'Run the pipeline.'],
      ['.claude/rules/general.md', 'General rules.'],
    ]);
    expect(checkReply(PLAN, reply)).toEqual([{ path: 'CLAUDE.md', message: 'is missing the heading "## Rules"' }]);
  });

  it('F-04 AC-030 accepts a heading with CRLF line endings and trailing spaces', () => {
    const reply = replyOf([
      ['CLAUDE.md', '# Project\r\n## Goal  \r\nSome goal.\r\n## Rules\r\n'],
      ['.claude/commands/pipeline.md', 'Run the pipeline.'],
      ['.claude/rules/general.md', 'General rules.'],
    ]);
    expect(checkReply(PLAN, reply)).toEqual([]);
  });

  it('F-04 AC-030 does not require headings of a layout that is not Markdown', () => {
    const plan: GeneratedPlan = { files: [file('config.json', '## not a heading here')] };
    expect(checkReply(plan, replyOf([['config.json', '{"a": 1}']]))).toEqual([]);
  });

  it('F-04 AC-030 headingsOf returns the ## lines of a layout in order and not the ### lines', () => {
    expect(headingsOf('# Title\n## First\n### Nested\n## Second\n')).toEqual(['## First', '## Second']);
    expect(headingsOf('### Only nested\n#  Not level two')).toEqual([]);
    expect(headingsOf('')).toEqual([]);
  });

  it('F-04 AC-031 names the path that refers to SDDBuilder', () => {
    const reply = replyOf([
      ['CLAUDE.md', VALID_TEXT],
      ['.claude/commands/pipeline.md', 'Generated by SDDBuilder.'],
      ['.claude/rules/general.md', 'General rules.'],
    ]);
    expect(checkReply(PLAN, reply)).toEqual([
      { path: '.claude/commands/pipeline.md', message: 'refers to SDDBuilder\'s own files ("SDDBuilder")' },
    ]);
  });

  it.each(['source/apps/web', 'source/apps/api', 'source/packages/core'])(
    'F-04 AC-031 names the path that refers to %s',
    (term) => {
      const reply = replyOf([
        ['CLAUDE.md', VALID_TEXT],
        ['.claude/commands/pipeline.md', `Read ${term}/index.ts first.`],
        ['.claude/rules/general.md', 'General rules.'],
      ]);
      expect(checkReply(PLAN, reply)).toEqual([
        { path: '.claude/commands/pipeline.md', message: `refers to SDDBuilder's own files ("${term}")` },
      ]);
    },
  );

  it.each([
    'The source/apps folder of this project.',
    'Keep the SDD builder notes in the sddbuilder docs folder.',
    'Read source/apps/website/index.ts and source/packages/core-utils/README.md.',
    'The api of source/apps/api-docs is out of scope.',
  ])('F-04 AC-031 does not flag an ordinary word or a longer path name: %s', (text) => {
    const reply = replyOf([
      ['CLAUDE.md', VALID_TEXT],
      ['.claude/commands/pipeline.md', text],
      ['.claude/rules/general.md', 'General rules.'],
    ]);
    expect(checkReply(PLAN, reply)).toEqual([]);
  });

  it('F-04 AC-033 sorts the findings by path, then by message', () => {
    const reply = replyOf([
      ['CLAUDE.md', 'Mentions SDDBuilder.'],
      ['.claude/commands/pipeline.md', 'Mentions SDDBuilder and source/apps/web.'],
      ['.claude/rules/general.md', 42],
    ]);
    expect(checkReply(PLAN, reply)).toEqual([
      { path: '.claude/commands/pipeline.md', message: 'refers to SDDBuilder\'s own files ("SDDBuilder")' },
      { path: '.claude/commands/pipeline.md', message: 'refers to SDDBuilder\'s own files ("source/apps/web")' },
      { path: '.claude/rules/general.md', message: 'is not a string' },
      { path: 'CLAUDE.md', message: 'is missing the heading "## Goal"' },
      { path: 'CLAUDE.md', message: 'is missing the heading "## Rules"' },
      { path: 'CLAUDE.md', message: 'refers to SDDBuilder\'s own files ("SDDBuilder")' },
    ]);
  });

  it('F-04 AC-033 gives the same findings when the same reply is checked twice, and changes neither input', () => {
    const reply = replyOf([
      ['CLAUDE.md', 'Mentions SDDBuilder.'],
      ['extra.md', 'Extra text.'],
    ]);
    const planBefore = structuredClone(PLAN);
    const replyBefore = new Map(reply);

    const first = checkReply(PLAN, reply);
    const second = checkReply(PLAN, reply);

    expect(second).toEqual(first);
    expect(PLAN).toEqual(planBefore);
    expect(reply).toEqual(replyBefore);
  });
});
